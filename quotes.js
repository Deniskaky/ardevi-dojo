// Helper: Deterministic daily quote index based on date
function getTodayQuote() {
  const dayOfYear = Math.floor(Date.now() / 86400000);
  const idx = dayOfYear % BUSHIDO_QUOTES.length;
  return {
    ...BUSHIDO_QUOTES[idx],
    dayNumber: (dayOfYear % 30) + 1
  };
}
